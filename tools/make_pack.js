/* ---------------------------------------------------------------------------
 * File      : 1-5731n/tools/make_pack.js
 * Version   : 1.2.0
 * Role      : Authoring aid: builds a puzzle pack (base library or add-on) from the graded samples written by grade_distribution.js.
 * Depends on: Node.js ; ../engine.js ; sample files from tools/grade_distribution.js --out
 * Called by : by hand: node tools/make_pack.js --base samples_1.json samples_2.json ... | --id ultimate --name Ultimate --min-raw 230 --count 100 samples_*.json
 * Produces  : lib_base.js (--base) or <id>.json (add-on), plus a summary on stdout
 * Changelog : see CHANGELOG.md
 * ---------------------------------------------------------------------------
 * A pack is a list of puzzle codes with their raw score: { format, id, name, gen, scale, puzzles: [[code, raw], ...] }.
 * The game recomputes the level of every puzzle itself; the score stored here only helps to choose.
 *
 *   --base            writes lib_base.js : PER_LEVEL puzzles for each of the 5 levels (a fixed shuffle, so the file is reproducible).
 *                     The ORDER of this file is frozen once published: the puzzle of the day indexes into it (see library.js).
 *   --id --name       add-on: id (lower case letters, digits, dashes) and display name
 *   --min-raw N       add-on: only puzzles with a raw score >= N
 *   --count N         add-on: keep the N hardest (default: all that qualify)
 *   --per-level N     base: puzzles per level (default 500)
 *   --out FILE        output file (default lib_base.js or <id>.json, in the current directory)
 */
'use strict';
const path = require('path');
const fs = require('fs');
const E = require(path.join(__dirname, '..', 'engine.js'));

const argv = process.argv.slice(2);
const opt = {}, files = [];
for (let i = 0; i < argv.length; i++) {
  const a = argv[i];
  if (a === '--base') opt.base = true;
  else if (/^--(id|name|min-raw|count|per-level|out)$/.test(a)) opt[a.slice(2)] = argv[++i];
  else files.push(a);
}
if (!files.length || (!opt.base && !opt.id)) { console.error('usage: see the header of this file'); process.exit(2); }

let samples = [];
files.forEach(f => { samples = samples.concat(JSON.parse(fs.readFileSync(f, 'utf8'))); });
const seen = new Set();
samples = samples.filter(s => !seen.has(s.code) && seen.add(s.code));
console.log('samples (distinct):', samples.length);

// the generation algorithm and the scale the pack belongs to
const pack = (id, name, rows) => ({ format: 1, id: id, name: name, gen: E.CODE_VERSION, scale: E.SCALE_VERSION, puzzles: rows.map(s => [s.code, s.raw]) });

// small seeded shuffle (mulberry32), integer arithmetic only: same order on every machine
function shuffled(arr, seed) {
  const a = arr.slice(); let x = seed >>> 0;
  const rnd = () => { x = (x + 0x6D2B79F5) >>> 0; let t = x; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); const t = a[i]; a[i] = a[j]; a[j] = t; }
  return a;
}

if (opt.base) {
  const per = parseInt(opt['per-level'] || '500', 10);
  let rows = [];
  for (let lv = 0; lv < E.LEVEL_COUNT; lv++) {
    const pool = samples.filter(s => E.levelOf(s.raw) === lv);
    const pick = shuffled(pool, 1000 + lv).slice(0, per);
    console.log('level', lv, ': available', pool.length, ', kept', pick.length);
    rows = rows.concat(pick);                                  // file order = level 0 first, then 1, ... : frozen
  }
  const p = pack('base', 'Base', rows);
  const out = opt.out || 'lib_base.js';
  const header = '/* ---------------------------------------------------------------------------\n' +
    ' * File      : 1-5731n/lib_base.js\n * Version   : 1.0.0\n' +
    ' * Role      : Base puzzle library: ' + per + ' puzzle codes (with their raw score) for each of the five levels.\n' +
    ' * Depends on: library.js (SteinLib.addBase)\n * Called by : index.html (script tag) ; worker-free ; test_library.js\n' +
    ' * Produces  : the "base" pack, registered in window.SteinLib\n * Changelog : see CHANGELOG.md\n' +
    ' * ---------------------------------------------------------------------------\n' +
    ' * Generated by tools/make_pack.js --base. Do not edit by hand. The ORDER is frozen: the puzzle of the day indexes into it.\n */\n';
  fs.writeFileSync(out, header + 'SteinLib.addBase(' + JSON.stringify(p) + ');\n');
  console.log('written', out, '(' + p.puzzles.length + ' puzzles,', fs.statSync(out).size, 'bytes)');
} else {
  if (!/^[a-z0-9-]{1,32}$/.test(opt.id)) { console.error('--id: lower case letters, digits and dashes (1-32)'); process.exit(2); }
  const min = parseInt(opt['min-raw'] || '0', 10);
  let pool = samples.filter(s => s.raw >= min).sort((a, b) => b.raw - a.raw);
  if (opt.count) pool = pool.slice(0, parseInt(opt.count, 10));
  const p = pack(opt.id, opt.name || opt.id, pool);
  const out = opt.out || opt.id + '.json';
  fs.writeFileSync(out, JSON.stringify(p));
  console.log('written', out, '(' + p.puzzles.length + ' puzzles, raw', pool.length ? pool[pool.length - 1].raw + '..' + pool[0].raw : '-', ',', fs.statSync(out).size, 'bytes)');
}
